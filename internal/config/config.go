// Пакет config отвечает за сбор, парсинг и валидацию конфигурационных
// параметров накопительной системы лояльности «Гофермарт».
//
// Конфигурирование приложения поддерживает гибкую настройку через флаги
// командной строки и переменные окружения операционной системы (ENV) по ТЗ.
// Загрузчик автоматически соблюдает стандартный приоритет Go-приложений:
// значения из переменных окружения имеют высший приоритет и переопределяют флаги.
package config

import (
	"fmt"
	"os"
	"time"

	"github.com/ioncode/confy"
)

// Config инкапсулирует все параметры конфигурации, необходимые для запуска
// и корректного функционирования сервиса накопительной системы лояльности.
type Config struct {
	// RunAddress определяет сетевой адрес и порт, на которых будет запущен HTTP-сервер.
	// Конфигурируется через переменную окружения RUN_ADDRESS или флаг командной строки -a.
	RunAddress string `flag:"a" env:"RUN_ADDRESS" default:"localhost:8080" desc:"адрес и порт запуска сервиса"`

	// DatabaseURI содержит строку подключения (Data Source Name) к СУБД PostgreSQL.
	// Является обязательным параметром (required). Конфигурируется через переменную
	// окружения DATABASE_URI или флаг командной строки -d.
	DatabaseURI string `flag:"d" env:"DATABASE_URI" required:"true"         desc:"адрес подключения к базе данных"`

	// AccrualSystemAddress задает базовый URL-адрес внешней системы расчета начислений.
	// Используется фоновым воркером для опроса статусов. Конфигурируется через переменную
	// окружения ACCRUAL_SYSTEM_ADDRESS или флаг командной строки -r.
	AccrualSystemAddress string `flag:"r" env:"ACCRUAL_SYSTEM_ADDRESS" default:"http://localhost:8081" desc:"адрес системы расчёта начислений"`

	// JWTSecret содержит секретный криптографический ключ для подписи и валидации JWT-токенов.
	// Используется слоем аутентификации в AuthMiddleware для защиты приватных эндпоинтов.
	JWTSecret string `env:"JWT_SECRET"           default:"super-secret-key-change-me-in-production" desc:"jwt secret key"`

	// TokenTTL определяет время жизни (Time To Live) сессионного токена авторизации пользователя.
	// По истечении этого периода кука сессии становится невалидной, требуя повторного входа.
	TokenTTL time.Duration `env:"TOKEN_TTL"           default:"24h"                                        desc:"token time to live"`
}

// Load считывает, парсит и валидирует конфигурационные параметры приложения.
//
// Функция инициализирует загрузчик confy, передавая ему аргументы командной строки.
// Процесс парсинга автоматически обрабатывает теги структуры Config, применяя
// значения по умолчанию (default), проверяя обязательные поля (required) и
// соблюдая приоритет переменных окружения над флагами CLI по требованиям ТЗ.
//
// Возвращаемые значения:
//   - *Config: указатель на заполненную структуру конфигурации при успешном парсинге.
//   - error: ошибка валидации (например, если не передан обязательный DATABASE_URI).
func Load() (*Config, error) {
	var cfg Config

	// Инициализируем загрузчик confy.
	// Первый параметр (префикс env-переменных) оставляем пустым "", так как по ТЗ
	// переменные окружения не имеют общего системного префикса.
	// Второй параметр передает аргументы командной строки, исключая имя самого бинарника.
	loader := confy.New("", os.Args[1:])

	// Выполняем потоковую загрузку и автоматическую валидацию полей структуры.
	if err := loader.Load(&cfg); err != nil {
		return nil, fmt.Errorf("failed to load configuration via confy loader: %w", err)
	}

	return &cfg, nil
}
